// Regenerates src/sources/cityServicesData.ts from a captured catalog.json (see docs/sources.md).
// Usage: node scripts/gen-city-services.mjs <path/to/catalog.json>
// Values are copied unchanged; rows are sorted by the numeric id in the service URL so paging is stable.
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/gen-city-services.mjs <catalog.json>");
  process.exit(2);
}
const { count, items } = JSON.parse(readFileSync(input, "utf8"));
if (items.length !== count) throw new Error(`count ${count} != items ${items.length}`);
const URL_RE = /^https:\/\/servicos\.curitiba\.pr\.gov\.br\/[a-z0-9-]+\/(\d+)$/;
const rows = items.map((x) => {
  const m = URL_RE.exec(x.url);
  if (!m) throw new Error(`bad url ${x.url}`);
  if (typeof x.title !== "string" || typeof x.what !== "string" || typeof x.cat !== "string") throw new Error(`bad item ${x.url}`);
  if (x.online !== null && typeof x.online !== "string") throw new Error(`bad online ${x.url}`);
  return { id: Number(m[1]), ...x };
});
rows.sort((a, b) => a.id - b.id);
const categories = [...new Set(rows.map((r) => r.cat))].sort((a, b) => a.localeCompare(b, "pt-BR"));
const lines = rows.map((r) => `  ${JSON.stringify([categories.indexOf(r.cat), r.title, r.what, r.url, r.online])},`);
const out = `// Generated by scripts/gen-city-services.mjs; do not edit by hand.
// Prefeitura Municipal de Curitiba — Carta de Serviços, listing pages of https://www.curitiba.pr.gov.br/servicos/
// Captured 2026-11-19/20 with a scripted browser session (a real browser, one listing page at a time, about one page every few seconds), listing pages of https://www.curitiba.pr.gov.br/servicos/ only; detail pages on servicos.curitiba.pr.gov.br were never opened.
// Values as published. Prefeitura content, not under this repository's Apache-2.0 licence: see NOTICE.

export const CATEGORIES = ${JSON.stringify(categories)} as const;

/** [category index, title, "O que é?" teaser as published, official URL, online URL or null], sorted by id. */
export const ROWS: readonly (readonly [number, string, string, string, string | null])[] = [
${lines.join("\n")}
];
`;
writeFileSync(new URL("../src/sources/cityServicesData.ts", import.meta.url), out);
console.log(`wrote ${rows.length} rows, ${categories.length} categories`);
